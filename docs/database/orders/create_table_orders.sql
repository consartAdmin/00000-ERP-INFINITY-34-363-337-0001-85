BEGIN;

-----------------------------------------------------------------------
-- Create the new commercial orders table
-----------------------------------------------------------------------

CREATE TABLE public.orders (
    --------------------------------------------------------------------
    -- Identification
    --------------------------------------------------------------------
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    issue_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status     VARCHAR(40) NOT NULL DEFAULT 'ABERTO',

    --------------------------------------------------------------------
    -- Origin
    -- Optional reference to the budget that generated this order
    --------------------------------------------------------------------
    budget_id BIGINT,

    --------------------------------------------------------------------
    -- Customer snapshot
    --------------------------------------------------------------------
    customer_id     BIGINT,
    customer_name   VARCHAR(200) NOT NULL,
    customer_tax_id VARCHAR(32) NOT NULL,
    customer_email  VARCHAR(180),
    customer_phone  VARCHAR(30),

    --------------------------------------------------------------------
    -- Commercial relationships
    --------------------------------------------------------------------
    seller_id          VARCHAR,
    price_id           INTEGER,
    operation_type_id  BIGINT,
    payment_form_id    BIGINT,
    payment_term_id    BIGINT,
    order_shipping_id  INTEGER,

    --------------------------------------------------------------------
    -- Commercial totals
    --------------------------------------------------------------------
    subtotal               NUMERIC(14,2) NOT NULL DEFAULT 0,
    items_discount_total   NUMERIC(14,2) NOT NULL DEFAULT 0,

    global_discount_type   VARCHAR(20) NOT NULL DEFAULT 'value',
    global_discount_value  NUMERIC(14,2) NOT NULL DEFAULT 0,
    global_discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0,

    total_discount         NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_amount           NUMERIC(14,2) NOT NULL DEFAULT 0,

    --------------------------------------------------------------------
    -- Additional information
    --------------------------------------------------------------------
    notes TEXT,

    --------------------------------------------------------------------
    -- Audit
    --------------------------------------------------------------------
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    --------------------------------------------------------------------
    -- Primary key
    --------------------------------------------------------------------
    CONSTRAINT orders_pkey
        PRIMARY KEY (order_id),

    --------------------------------------------------------------------
    -- Foreign keys
    --------------------------------------------------------------------

    -- Budget that originated the order
    CONSTRAINT fk_orders_budget
        FOREIGN KEY (budget_id)
        REFERENCES public.budgets (budget_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_orders_price
        FOREIGN KEY (price_id)
        REFERENCES public.prices (price_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_orders_operation_type
        FOREIGN KEY (operation_type_id)
        REFERENCES public."nfeOperationTypes" (operation_type_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_orders_shipping
        FOREIGN KEY (order_shipping_id)
        REFERENCES public."ordersShipping" (order_shipping_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    --------------------------------------------------------------------
    -- Validation
    --------------------------------------------------------------------
    CONSTRAINT ck_orders_status
        CHECK (BTRIM(status) <> ''),

    CONSTRAINT ck_orders_customer_name
        CHECK (BTRIM(customer_name) <> ''),

    CONSTRAINT ck_orders_customer_tax_id
        CHECK (BTRIM(customer_tax_id) <> ''),

    CONSTRAINT ck_orders_discount_type
        CHECK (
            global_discount_type IN (
                'value',
                'percent'
            )
        ),

    CONSTRAINT ck_orders_values
        CHECK (
            subtotal >= 0
            AND items_discount_total >= 0
            AND global_discount_value >= 0
            AND global_discount_amount >= 0
            AND total_discount >= 0
            AND total_amount >= 0
        )
);

-----------------------------------------------------------------------
-- Enforce one shipping record per order
-----------------------------------------------------------------------

CREATE UNIQUE INDEX uq_orders_shipping
    ON public.orders (order_shipping_id)
    WHERE order_shipping_id IS NOT NULL;

-----------------------------------------------------------------------
-- Search and relationship indexes
-----------------------------------------------------------------------

CREATE INDEX idx_orders_issue_date
    ON public.orders (issue_date);

CREATE INDEX idx_orders_status
    ON public.orders (status);

CREATE INDEX idx_orders_budget_id
    ON public.orders (budget_id)
    WHERE budget_id IS NOT NULL;

CREATE INDEX idx_orders_customer_id
    ON public.orders (customer_id)
    WHERE customer_id IS NOT NULL;

CREATE INDEX idx_orders_customer_name
    ON public.orders (LOWER(customer_name));

CREATE INDEX idx_orders_customer_tax_id
    ON public.orders (customer_tax_id);

CREATE INDEX idx_orders_customer_email
    ON public.orders (LOWER(customer_email))
    WHERE customer_email IS NOT NULL;

CREATE INDEX idx_orders_seller_id
    ON public.orders (seller_id)
    WHERE seller_id IS NOT NULL;

CREATE INDEX idx_orders_price_id
    ON public.orders (price_id)
    WHERE price_id IS NOT NULL;

CREATE INDEX idx_orders_operation_type_id
    ON public.orders (operation_type_id)
    WHERE operation_type_id IS NOT NULL;

CREATE INDEX idx_orders_payment_form_id
    ON public.orders (payment_form_id)
    WHERE payment_form_id IS NOT NULL;

CREATE INDEX idx_orders_payment_term_id
    ON public.orders (payment_term_id)
    WHERE payment_term_id IS NOT NULL;

-----------------------------------------------------------------------
-- updated_at trigger function
-----------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_updated_at_orders()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_orders_updated_at
BEFORE UPDATE ON public.orders
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at_orders();

COMMIT;