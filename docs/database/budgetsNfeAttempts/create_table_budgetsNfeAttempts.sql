BEGIN;


CREATE TABLE public."budgetsNfeAttempts" (
    attempt_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    budget_id         BIGINT NOT NULL,
    invoice_id        BIGINT,
    attempt_number    INTEGER NOT NULL DEFAULT 1,
    nfe_status_id     INTEGER NOT NULL,
    nfe_number        BIGINT,
    nfe_series        INTEGER,
    nfe_environment   VARCHAR(20),
    operation_type_id BIGINT,

    customer_id       BIGINT,
    customer_name     VARCHAR(240),
    customer_tax_id   VARCHAR(30),
    customer_email    VARCHAR(180),
    customer_phone    VARCHAR(30),

    issue_date        DATE,

    subtotal          NUMERIC(14,2) NOT NULL DEFAULT 0,
    discount_total    NUMERIC(14,2) NOT NULL DEFAULT 0,
    freight_value     NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_amount      NUMERIC(14,2) NOT NULL DEFAULT 0,

    provider_id       VARCHAR(120),
    integration_id    VARCHAR(160),
    access_key        VARCHAR(44),
    protocol          VARCHAR(100),

    request_payload   JSONB,
    provider_response JSONB,
    generated_xml     TEXT,

    error_code        VARCHAR(80),
    error_message     TEXT,

    requested_by      BIGINT,
    requested_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    authorized_at     TIMESTAMPTZ,
    rejected_at       TIMESTAMPTZ,
    last_checked_at   TIMESTAMPTZ,

-- Stock and cancellation control before timestamps
stock_applied_at  TIMESTAMPTZ,
    cancelled_at      TIMESTAMPTZ,
    stock_reversed_at TIMESTAMPTZ,

    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT "budgetsNfeAttempts_pkey"
        PRIMARY KEY (attempt_id),

    CONSTRAINT "uq_budget_nfe_attempt_number"
        UNIQUE (budget_id, attempt_number),

    CONSTRAINT "fk_budget_nfe_attempt_budget"
        FOREIGN KEY (budget_id)
        REFERENCES public.budgets (budget_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT "fk_budget_nfe_attempt_invoice"
        FOREIGN KEY (invoice_id)
        REFERENCES public."invoicesIssued" (invoice_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT "fk_budget_nfe_attempt_operation"
        FOREIGN KEY (operation_type_id)
        REFERENCES public."nfeOperationTypes" (operation_type_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT "fk_budget_nfe_attempt_status"
        FOREIGN KEY (nfe_status_id)
        REFERENCES public."nfeStatusMap" (nfe_status_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- ============================================================
-- 3. Recreate regular indexes
-- ============================================================

CREATE INDEX "ix_budget_nfe_attempt_budget"
    ON public."budgetsNfeAttempts" (budget_id);

CREATE INDEX "ix_budget_nfe_attempt_invoice"
    ON public."budgetsNfeAttempts" (invoice_id);

CREATE INDEX "ix_budget_nfe_attempt_operation"
    ON public."budgetsNfeAttempts" (operation_type_id);

CREATE INDEX "ix_budget_nfe_attempt_requested_at"
    ON public."budgetsNfeAttempts" (requested_at DESC);

CREATE INDEX "ix_budget_nfe_attempt_status"
    ON public."budgetsNfeAttempts" (nfe_status_id);

-- ============================================================
-- 4. Recreate unique partial indexes
-- ============================================================

CREATE UNIQUE INDEX "ux_budget_nfe_attempt_access_key"
    ON public."budgetsNfeAttempts" (access_key)
    WHERE access_key IS NOT NULL
      AND BTRIM(access_key) <> '';

CREATE UNIQUE INDEX "ux_budget_nfe_attempt_provider"
    ON public."budgetsNfeAttempts" (provider_id)
    WHERE provider_id IS NOT NULL
      AND BTRIM(provider_id) <> '';

-- ============================================================
-- 5. Recreate stock-control partial indexes
-- ============================================================

CREATE INDEX "idx_budgetsNfeAttempts_cancelled"
    ON public."budgetsNfeAttempts" (cancelled_at)
    WHERE cancelled_at IS NOT NULL;

CREATE INDEX "idx_budgetsNfeAttempts_stock_pending"
    ON public."budgetsNfeAttempts" (attempt_id)
    WHERE authorized_at IS NOT NULL
      AND stock_applied_at IS NULL;

CREATE INDEX "idx_budgetsNfeAttempts_stock_reversal_pending"
    ON public."budgetsNfeAttempts" (attempt_id)
    WHERE stock_applied_at IS NOT NULL
      AND cancelled_at IS NOT NULL
      AND stock_reversed_at IS NULL;

-- ============================================================
-- 6. Reconnect the attempt-items table
-- ============================================================

ALTER TABLE public."budgetsNfeAttemptItems"
ADD CONSTRAINT "fk_budgetsNfeAttemptItems_attempt"
FOREIGN KEY (attempt_id)
REFERENCES public."budgetsNfeAttempts" (attempt_id)
ON UPDATE CASCADE
ON DELETE CASCADE;

COMMIT;