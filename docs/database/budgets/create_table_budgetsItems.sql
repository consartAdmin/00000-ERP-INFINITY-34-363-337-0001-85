BEGIN;

-----------------------------------------------------------------------
-- Create final budgetsItems table
-----------------------------------------------------------------------

CREATE TABLE public."budgetsItems" (
    --------------------------------------------------------------------
    -- Identification
    --------------------------------------------------------------------
    budget_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    budget_id      BIGINT NOT NULL,

--------------------------------------------------------------------
-- Product and commercial presentation
--------------------------------------------------------------------
product_code VARCHAR(80) NOT NULL,
barcode_id BIGINT,
description VARCHAR(240) NOT NULL,
manufacturer_ref VARCHAR(100),
grade_id INTEGER,
unit_code VARCHAR(50) NOT NULL,
conversion_factor NUMERIC(14, 6) NOT NULL DEFAULT 1,

--------------------------------------------------------------------
-- Commercial values
--------------------------------------------------------------------
quantity NUMERIC(14, 3) NOT NULL DEFAULT 0,
unit_price NUMERIC(14, 4) NOT NULL DEFAULT 0,
discount_value NUMERIC(14, 4) NOT NULL DEFAULT 0,

--------------------------------------------------------------------
-- Price and commission
--------------------------------------------------------------------
price_id INTEGER, commission_id BIGINT,

--------------------------------------------------------------------
-- Stock and lot
--------------------------------------------------------------------
lot_id BIGINT,

--------------------------------------------------------------------
-- Stock override
--------------------------------------------------------------------
override_stock BOOLEAN NOT NULL DEFAULT FALSE,
override_token TEXT,
override_approved_at TIMESTAMPTZ,
override_approved_by VARCHAR(50),
override_reason TEXT,
override_qty NUMERIC(14, 3),
override_lot_id BIGINT,

--------------------------------------------------------------------
-- Audit
--------------------------------------------------------------------
created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

--------------------------------------------------------------------
-- Primary key
--------------------------------------------------------------------
CONSTRAINT budgets_items_pkey PRIMARY KEY (budget_item_id),

--------------------------------------------------------------------
-- Budget
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_budget FOREIGN KEY (budget_id) REFERENCES public.budgets (budget_id) ON UPDATE CASCADE ON DELETE CASCADE,

--------------------------------------------------------------------
-- Product
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_product FOREIGN KEY (product_code) REFERENCES public.products (product_code) ON UPDATE CASCADE ON DELETE RESTRICT,

--------------------------------------------------------------------
-- Selected barcode/presentation
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_barcode
        FOREIGN KEY (barcode_id)
        REFERENCES public."productsBarCode" (barcode_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

--------------------------------------------------------------------
-- Grade
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_grade FOREIGN KEY (grade_id) REFERENCES public.grades (grade_id) ON UPDATE CASCADE ON DELETE RESTRICT,

--------------------------------------------------------------------
-- Price table
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_price FOREIGN KEY (price_id) REFERENCES public.prices (price_id) ON UPDATE CASCADE ON DELETE RESTRICT,

--------------------------------------------------------------------
-- Commission
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_commission
        FOREIGN KEY (commission_id)
        REFERENCES public."priceCommissions" (commission_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

--------------------------------------------------------------------
-- Selected stock lot
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_lot
        FOREIGN KEY (lot_id)
        REFERENCES public."productsStockLots" (lot_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

--------------------------------------------------------------------
-- Override stock lot
--------------------------------------------------------------------
CONSTRAINT fk_budgets_items_override_lot
        FOREIGN KEY (override_lot_id)
        REFERENCES public."productsStockLots" (lot_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

--------------------------------------------------------------------
-- Required text validation
--------------------------------------------------------------------
CONSTRAINT ck_budgets_items_product_code CHECK (BTRIM (product_code) <> ''),
CONSTRAINT ck_budgets_items_description CHECK (BTRIM (description) <> ''),
CONSTRAINT ck_budgets_items_unit_code CHECK (BTRIM (unit_code) <> ''),

--------------------------------------------------------------------
-- Commercial value validation
--------------------------------------------------------------------
CONSTRAINT ck_budgets_items_values CHECK (
    quantity >= 0
    AND unit_price >= 0
    AND discount_value >= 0
),

--------------------------------------------------------------------
-- Conversion factor validation
--------------------------------------------------------------------
CONSTRAINT ck_budgets_items_conversion_factor CHECK (conversion_factor > 0),

--------------------------------------------------------------------
-- Override quantity validation
--------------------------------------------------------------------
CONSTRAINT ck_budgets_items_override_qty CHECK (
    override_qty IS NULL
    OR override_qty >= 0
),

--------------------------------------------------------------------
-- Basic stock override consistency
--------------------------------------------------------------------
CONSTRAINT ck_budgets_items_override_data
        CHECK (
            override_stock = TRUE
            OR (
                override_token IS NULL
                AND override_approved_at IS NULL
                AND override_approved_by IS NULL
                AND override_reason IS NULL
                AND override_qty IS NULL
                AND override_lot_id IS NULL
            )
        )
);

-----------------------------------------------------------------------
-- Indexes
-----------------------------------------------------------------------

CREATE INDEX idx_budgets_items_budget_id
    ON public."budgetsItems" (budget_id);

CREATE INDEX idx_budgets_items_product_code
    ON public."budgetsItems" (product_code);

CREATE INDEX idx_budgets_items_barcode_id
    ON public."budgetsItems" (barcode_id)
    WHERE barcode_id IS NOT NULL;

CREATE INDEX idx_budgets_items_grade_id
    ON public."budgetsItems" (grade_id)
    WHERE grade_id IS NOT NULL;

CREATE INDEX idx_budgets_items_price_id
    ON public."budgetsItems" (price_id)
    WHERE price_id IS NOT NULL;

CREATE INDEX idx_budgets_items_commission_id
    ON public."budgetsItems" (commission_id)
    WHERE commission_id IS NOT NULL;

CREATE INDEX idx_budgets_items_lot_id
    ON public."budgetsItems" (lot_id)
    WHERE lot_id IS NOT NULL;

CREATE INDEX idx_budgets_items_override_lot_id
    ON public."budgetsItems" (override_lot_id)
    WHERE override_lot_id IS NOT NULL;

CREATE INDEX idx_budgets_items_override_stock
    ON public."budgetsItems" (override_stock)
    WHERE override_stock = TRUE;

CREATE INDEX idx_budgets_items_budget_product
    ON public."budgetsItems" (
        budget_id,
        product_code
    );

CREATE INDEX idx_budgets_items_budget_barcode
    ON public."budgetsItems" (
        budget_id,
        barcode_id
    )
    WHERE barcode_id IS NOT NULL;

-----------------------------------------------------------------------
-- updated_at trigger function
-----------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_updated_at_budgets_items()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

-----------------------------------------------------------------------
-- updated_at trigger
-----------------------------------------------------------------------

CREATE TRIGGER trg_budgets_items_updated_at
BEFORE UPDATE ON public."budgetsItems"
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at_budgets_items();

COMMIT;