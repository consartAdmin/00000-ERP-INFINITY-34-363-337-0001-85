BEGIN;

-----------------------------------------------------------------------
-- Create the new commercial budgets table
-----------------------------------------------------------------------


CREATE TABLE public.budgets (
    --------------------------------------------------------------------
    -- Identification
    --------------------------------------------------------------------
    budget_id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    issue_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status     VARCHAR(40) NOT NULL DEFAULT 'ABERTO',

--------------------------------------------------------------------
-- Customer snapshot
--------------------------------------------------------------------
customer_id BIGINT,
customer_name VARCHAR(200) NOT NULL,
customer_tax_id VARCHAR(32) NOT NULL,
customer_email VARCHAR(180),
customer_phone VARCHAR(30),

--------------------------------------------------------------------
-- Commercial relationships
--------------------------------------------------------------------
seller_id VARCHAR,
price_id INTEGER,
operation_type_id BIGINT,
payment_form_id BIGINT,
payment_term_id BIGINT,
budget_shipping_id INTEGER,

--------------------------------------------------------------------
-- Commercial totals
--------------------------------------------------------------------
subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0,
items_discount_total NUMERIC(14, 2) NOT NULL DEFAULT 0,
global_discount_type VARCHAR(20) NOT NULL DEFAULT 'value',
global_discount_value NUMERIC(14, 2) NOT NULL DEFAULT 0,
global_discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
total_discount NUMERIC(14, 2) NOT NULL DEFAULT 0,
total_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,

--------------------------------------------------------------------
-- Additional information
--------------------------------------------------------------------
notes TEXT,

--------------------------------------------------------------------
-- Audit
--------------------------------------------------------------------
created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

--------------------------------------------------------------------
-- Primary key
--------------------------------------------------------------------
CONSTRAINT budgets_pkey PRIMARY KEY (budget_id),

--------------------------------------------------------------------
-- Foreign keys
--------------------------------------------------------------------
CONSTRAINT fk_budgets_price
        FOREIGN KEY (price_id)
        REFERENCES public.prices (price_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_budgets_operation_type
        FOREIGN KEY (operation_type_id)
        REFERENCES public."nfeOperationTypes" (operation_type_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_budgets_shipping
        FOREIGN KEY (budget_shipping_id)
        REFERENCES public."budgetsShipping" (budget_shipping_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

--------------------------------------------------------------------
-- Validation
--------------------------------------------------------------------
CONSTRAINT ck_budgets_status
        CHECK (BTRIM(status) <> ''),

    CONSTRAINT ck_budgets_customer_name
        CHECK (BTRIM(customer_name) <> ''),

    CONSTRAINT ck_budgets_customer_tax_id
        CHECK (BTRIM(customer_tax_id) <> ''),

    CONSTRAINT ck_budgets_discount_type
        CHECK (
            global_discount_type IN (
                'value',
                'percent'
            )
        ),

    CONSTRAINT ck_budgets_values
        CHECK (
            subtotal >= 0
            AND items_discount_total >= 0
            AND global_discount_value >= 0
            AND global_discount_amount >= 0
            AND total_discount >= 0
            AND total_amount >= 0
        )
);

-----------------------------------------------------------------------
-- Enforce one shipping record per budget
-----------------------------------------------------------------------

CREATE UNIQUE INDEX uq_budgets_shipping ON public.budgets (budget_shipping_id)
WHERE
    budget_shipping_id IS NOT NULL;

-----------------------------------------------------------------------
-- Search and relationship indexes
-----------------------------------------------------------------------

CREATE INDEX idx_budgets_issue_date ON public.budgets (issue_date);

CREATE INDEX idx_budgets_status ON public.budgets (status);

CREATE INDEX idx_budgets_customer_id ON public.budgets (customer_id)
WHERE
    customer_id IS NOT NULL;

CREATE INDEX idx_budgets_customer_name ON public.budgets (LOWER(customer_name));

CREATE INDEX idx_budgets_customer_tax_id ON public.budgets (customer_tax_id);

CREATE INDEX idx_budgets_customer_email ON public.budgets (LOWER(customer_email))
WHERE
    customer_email IS NOT NULL;

CREATE INDEX idx_budgets_seller_id ON public.budgets (seller_id)
WHERE
    seller_id IS NOT NULL;

CREATE INDEX idx_budgets_price_id ON public.budgets (price_id)
WHERE
    price_id IS NOT NULL;

CREATE INDEX idx_budgets_operation_type_id ON public.budgets (operation_type_id)
WHERE
    operation_type_id IS NOT NULL;

CREATE INDEX idx_budgets_payment_form_id ON public.budgets (payment_form_id)
WHERE
    payment_form_id IS NOT NULL;

CREATE INDEX idx_budgets_payment_term_id ON public.budgets (payment_term_id)
WHERE
    payment_term_id IS NOT NULL;

-----------------------------------------------------------------------

-- updated_at trigger function
-----------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_updated_at_budgets()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_budgets_updated_at
BEFORE UPDATE ON public.budgets
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at_budgets();

COMMIT;