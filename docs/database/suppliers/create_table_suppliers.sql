-----------------------------------------------------------------------
-- Create the suppliers table
-----------------------------------------------------------------------


CREATE TABLE public.suppliers (
    --------------------------------------------------------------------
    -- Identification
    --------------------------------------------------------------------
    supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    name               VARCHAR(200) NOT NULL,
    tax_id             VARCHAR(20),
    state_registration VARCHAR(30),

--------------------------------------------------------------------
-- Main contact
--------------------------------------------------------------------
phone VARCHAR(20), email VARCHAR(100),

--------------------------------------------------------------------
-- Portal credentials and additional information
--------------------------------------------------------------------
website VARCHAR(200),
login VARCHAR(150),
password VARCHAR(255),
observations TEXT,

--------------------------------------------------------------------
-- Address
--------------------------------------------------------------------
-- Legacy complete address kept for backward compatibility
address TEXT,
address_street VARCHAR(200),
address_number VARCHAR(30),
address_complement VARCHAR(120),
address_district VARCHAR(120),
city VARCHAR(100),
state VARCHAR(2),
postal_code VARCHAR(10),

--------------------------------------------------------------------
-- Commercial contacts
--------------------------------------------------------------------
sales_rep VARCHAR(100),
sales_rep_email VARCHAR(100),
finance_email VARCHAR(100),

--------------------------------------------------------------------
-- Default financial classification
--------------------------------------------------------------------
chart_account_id INTEGER,
cash_category_id INTEGER,
cash_subcategory_id INTEGER,

--------------------------------------------------------------------
-- Audit
--------------------------------------------------------------------
created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

--------------------------------------------------------------------
-- Primary key
--------------------------------------------------------------------
CONSTRAINT suppliers_pkey PRIMARY KEY (supplier_id),

--------------------------------------------------------------------
-- Foreign keys
--------------------------------------------------------------------
CONSTRAINT fk_suppliers_chart_account
        FOREIGN KEY (chart_account_id)
        REFERENCES public."chartOfAccounts" (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_suppliers_cash_category
        FOREIGN KEY (cash_category_id)
        REFERENCES public."caixaCategorias" (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_suppliers_cash_subcategory
        FOREIGN KEY (cash_subcategory_id)
        REFERENCES public."caixaSubCategorias" (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

--------------------------------------------------------------------
-- Validation
--------------------------------------------------------------------
CONSTRAINT ck_suppliers_name
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT ck_suppliers_tax_id
        CHECK (
            tax_id IS NULL
            OR BTRIM(tax_id) <> ''
        ),

    CONSTRAINT ck_suppliers_state
        CHECK (
            state IS NULL
            OR state ~ '^[A-Z]{2}$'
        ),

    CONSTRAINT ck_suppliers_financial_category
        CHECK (
            cash_subcategory_id IS NULL
            OR cash_category_id IS NOT NULL
        )
);

-----------------------------------------------------------------------
-- Unique supplier document
-----------------------------------------------------------------------

CREATE UNIQUE INDEX suppliers_tax_id_uq ON public.suppliers (tax_id)
WHERE
    tax_id IS NOT NULL;

-----------------------------------------------------------------------
-- Search indexes
-----------------------------------------------------------------------

CREATE INDEX idx_suppliers_name ON public.suppliers (name);

CREATE INDEX idx_suppliers_city ON public.suppliers (city);

CREATE INDEX idx_suppliers_state ON public.suppliers (state);

-----------------------------------------------------------------------
-- Financial relationship indexes
-----------------------------------------------------------------------

CREATE INDEX idx_suppliers_chart_account ON public.suppliers (chart_account_id)
WHERE
    chart_account_id IS NOT NULL;

CREATE INDEX idx_suppliers_cash_category ON public.suppliers (cash_category_id)
WHERE
    cash_category_id IS NOT NULL;

CREATE INDEX idx_suppliers_cash_subcategory ON public.suppliers (cash_subcategory_id)
WHERE
    cash_subcategory_id IS NOT NULL;

-----------------------------------------------------------------------
-- Table and column documentation
-----------------------------------------------------------------------

COMMENT ON
TABLE public.suppliers IS 'Cadastro de fornecedores do CONSART ERP';

COMMENT ON COLUMN public.suppliers.address IS 'Endereço completo legado, mantido para compatibilidade';

COMMENT ON COLUMN public.suppliers.chart_account_id IS 'Conta contábil padrão do fornecedor';

COMMENT ON COLUMN public.suppliers.cash_category_id IS 'Categoria financeira padrão do fornecedor';

COMMENT ON COLUMN public.suppliers.cash_subcategory_id IS 'Subcategoria financeira padrão do fornecedor';

-----------------------------------------------------------------------
-- updated_at trigger function
-----------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_timestamp_suppliers()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_set_timestamp_suppliers
BEFORE UPDATE ON public.suppliers
FOR EACH ROW
EXECUTE FUNCTION public.set_timestamp_suppliers();

COMMIT;