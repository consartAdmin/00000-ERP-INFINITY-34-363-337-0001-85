// CRUD
// ======================================================================

const COLUMNS = [
    'regime', 'crt', 'valid_from', 'valid_to', 'description',
    'simples_annex', ...NUMERIC_COLUMNS, 'is_active',
];

export async function listTaxRegimes({ includeInactive = false } = {}) {
    await ensureTaxRegimesTable();

    const { rows } = await pool.query(
        `SELECT *
         FROM ${TABLE}
         WHERE ($1::boolean OR is_active = TRUE)
         ORDER BY valid_from DESC, tax_regime_id DESC`,
        [Boolean(includeInactive)]
    );

    return rows.map(mapRow);
}

export async function getTaxRegimeById(id) {
    await ensureTaxRegimesTable();

    const { rows } = await pool.query(
        `SELECT * FROM ${TABLE} WHERE tax_regime_id = $1`,
        [Number(id)]
    );

    return mapRow(rows[0]);
}

export async function createTaxRegime(input) {
    await ensureTaxRegimesTable();

    const data = sanitize(input);
    await assertNoOverlap(data);

    const { rows } = await pool.query(
        `INSERT INTO ${TABLE} (${COLUMNS.join(', ')})
         VALUES (${COLUMNS.map((_, index) => `$${index + 1}`).join(', ')})
         RETURNING *`,
        COLUMNS.map((column) => data[column])
    );

    return mapRow(rows[0]);
}

export async function updateTaxRegime(id, input) {
    await ensureTaxRegimesTable();

    const regimeId = Number(id);
    const data = sanitize(input);
    await assertNoOverlap(data, regimeId);

    const { rows } = await pool.query(
        `UPDATE ${TABLE}
         SET ${COLUMNS.map((column, index) => `${column} = $${index + 1}`).join(', ')},
             updated_at = NOW()
         WHERE tax_regime_id = $${COLUMNS.length + 1}
         RETURNING *`,
        [...COLUMNS.map((column) => data[column]), regimeId]
    );

    if (!rows.length) {
        throw httpError('Regime tributário não encontrado.', 404);
    }

    return mapRow(rows[0]);
}

export async function setTaxRegimeActive(id, isActive) {
    await ensureTaxRegimesTable();

    const current = await getTaxRegimeById(id);

    if (!current) {
        throw httpError('Regime tributário não encontrado.', 404);
    }

    if (isActive) {
        await assertNoOverlap({ ...current, is_active: true }, current.tax_regime_id);
    }

    const { rows } = await pool.query(
        `UPDATE ${TABLE}
         SET is_active = $1, updated_at = NOW()
         WHERE tax_regime_id = $2
         RETURNING *`,
        [Boolean(isActive), Number(id)]
    );

    return mapRow(rows[0]);
}


// ======================================================================
// LOOKUP BY DATE
// ======================================================================

export async function findTaxRegimeForDate(date) {
    await ensureTaxRegimesTable();

    const { rows } = await pool.query(
        `SELECT *
         FROM ${TABLE}
         WHERE is_active = TRUE
           AND valid_from <= $1::date
           AND (valid_to IS NULL OR valid_to >= $1::date)
         ORDER BY valid_from DESC, tax_regime_id DESC
         LIMIT 1`,
        [date]
    );

    return mapRow(rows[0]);
}
