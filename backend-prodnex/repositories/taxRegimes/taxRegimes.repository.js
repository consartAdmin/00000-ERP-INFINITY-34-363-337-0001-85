let tableReady = null;

export function ensureTaxRegimesTable() {
    tableReady ??= pool.query(`
        CREATE TABLE IF NOT EXISTS ${TABLE} (
            tax_regime_id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            regime                              VARCHAR(20) NOT NULL,
            crt                                 SMALLINT NOT NULL,
            valid_from                          DATE NOT NULL,
            valid_to                            DATE NULL,
            description                         TEXT NULL,

            simples_annex                       VARCHAR(5) NULL,
            rbt12                               NUMERIC(15,2) NULL,
            mei_monthly_das                     NUMERIC(15,2) NULL,

            irpj_presumption_pct                NUMERIC(7,4) NULL,
            csll_presumption_pct                NUMERIC(7,4) NULL,
            irpj_rate                           NUMERIC(7,4) NULL,
            irpj_additional_rate                NUMERIC(7,4) NULL,
            irpj_additional_monthly_threshold   NUMERIC(15,2) NULL,
            csll_rate                           NUMERIC(7,4) NULL,
            pis_rate                            NUMERIC(7,4) NULL,
            cofins_rate                         NUMERIC(7,4) NULL,
            estimated_profit_margin_pct         NUMERIC(7,4) NULL,

            is_active                           BOOLEAN NOT NULL DEFAULT TRUE,
            created_at                          TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
            updated_at                          TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),

            CONSTRAINT "taxRegimes_valid_range" CHECK (valid_to IS NULL OR valid_to >= valid_from)
        )
    `).then(() => pool.query(`
        CREATE INDEX IF NOT EXISTS "idx_taxRegimes_active_from"
            ON ${TABLE} (is_active, valid_from DESC)
    `)).catch((error) => {
        tableReady = null;
        throw error;
    });

    return tableReady;
}


// ======================================================================
// SANITIZE
// ======================================================================

function httpError(message, statusCode = 400) {
    const error = new Error(message);
    error.statusCode = statusCode;
    error.status = statusCode;
    return error;
}

function toDate(value) {
    const text = String(value ?? '').trim().slice(0, 10);
    return /^\d{4}-\d{2}-\d{2}$/.test(text) ? text : null;
}

function toNumberOrNull(value) {
    if (value === null || value === undefined || String(value).trim() === '') return null;
    const number = Number(String(value).replace(',', '.'));
    return Number.isFinite(number) ? number : null;
}

function sanitize(input = {}) {
    const regime = String(input.regime || '').trim().toUpperCase();

    if (!REGIMES[regime]) {
        throw httpError('Selecione um regime tributário válido.');
    }

    const validFrom = toDate(input.valid_from);
    const validTo = toDate(input.valid_to);

    if (!validFrom) {
        throw httpError('Informe a data de início da vigência.');
    }

    if (validTo && validTo < validFrom) {
        throw httpError('O fim da vigência não pode ser anterior ao início.');
    }

    const isSimples = regime === 'SIMPLES' || regime === 'SIMPLES_EXCESSO';
    const annex = String(input.simples_annex || '').trim().toUpperCase();

    if (isSimples && !SIMPLES_ANNEXES[annex]) {
        throw httpError('Selecione o anexo do Simples Nacional.');
    }

    const data = {
        regime,
        crt: REGIMES[regime].crt,
        valid_from: validFrom,
        valid_to: validTo,
        description: String(input.description ?? '').trim() || null,
        simples_annex: isSimples ? annex : null,
        is_active: input.is_active === undefined ? true : Boolean(input.is_active),
    };

    NUMERIC_COLUMNS.forEach((column) => {
        const value = toNumberOrNull(input[column]);

        if (value !== null && value < 0) {
            throw httpError('Os valores e alíquotas não podem ser negativos.');
        }

        data[column] = value;
    });

    return data;
}

function mapRow(row) {
    if (!row) return null;

    const out = { ...row };

    // node-pg returns DATE as a local-midnight Date; the UI works with YYYY-MM-DD.
    ['valid_from', 'valid_to'].forEach((column) => {
        const value = row[column];

        if (value instanceof Date) {
            out[column] = [
                value.getFullYear(),
                String(value.getMonth() + 1).padStart(2, '0'),
                String(value.getDate()).padStart(2, '0'),
            ].join('-');
        }
    });

    NUMERIC_COLUMNS.forEach((column) => {
        out[column] = row[column] === null ? null : Number(row[column]);
    });

    out.regime_label = REGIMES[row.regime]?.label || row.regime;
    out.simples_annex_label = SIMPLES_ANNEXES[row.simples_annex]?.label || null;

    return out;
}

async function assertNoOverlap(data, ignoreId = null) {
    if (!data.is_active) return;

    const { rows } = await pool.query(
        `SELECT tax_regime_id, valid_from, valid_to
         FROM ${TABLE}
         WHERE is_active = TRUE
           AND ($1::int IS NULL OR tax_regime_id <> $1)
           AND daterange(valid_from, COALESCE(valid_to, 'infinity'::date), '[]')
               && daterange($2::date, COALESCE($3::date, 'infinity'::date), '[]')
         LIMIT 1`,
        [ignoreId, data.valid_from, data.valid_to]
    );

    if (rows.length) {
        throw httpError(
            `Já existe um regime ativo nesse período (ID ${rows[0].tax_regime_id}). ` +
            'Encerre a vigência dele antes de cadastrar o novo.',
            409
        );
    }
}


