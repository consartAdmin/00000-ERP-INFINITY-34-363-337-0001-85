import pool from '../../config/db.js';
import { TABLE } from './cashDocumentTypes.constants.js';

export async function ensureCashDocumentTypesTable(client = pool) {
  await client.query(`
    CREATE TABLE IF NOT EXISTS ${TABLE} (
      id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name        VARCHAR(100) NOT NULL,
      is_active   BOOLEAN NOT NULL DEFAULT TRUE,
      created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
      updated_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
      CONSTRAINT "cashDocumentTypes_name_key" UNIQUE (name)
    )
  `);

  await client.query(`
    CREATE INDEX IF NOT EXISTS "idx_cashDocumentTypes_active_name"
      ON ${TABLE} (is_active, name)
  `);
}

export async function seedCashDocumentTypes(client = pool) {
  await ensureCashDocumentTypesTable(client);

  const names = ['NF-e', 'Cupom Fiscal', 'Outro', 'NFS-e', 'Boleto'];

  const { rows } = await client.query(
    `
      INSERT INTO ${TABLE} (name)
      SELECT name
        FROM UNNEST($1::VARCHAR[]) AS source(name)
      ON CONFLICT (name) DO UPDATE
        SET is_active = TRUE,
            updated_at = NOW()
      RETURNING id, name, is_active, created_at, updated_at
    `,
    [names]
  );

  return rows;
}
