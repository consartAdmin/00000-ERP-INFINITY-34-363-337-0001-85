import express from 'express';
import * as controller
  from '../controllers/betterDateToBuyController.js';

const router = express.Router();


// ──────────────────────────────────────────────────────────────────────
// GET ALL
// ──────────────────────────────────────────────────────────────────────
router.get(
  '/',
  controller.list
);


// ──────────────────────────────────────────────────────────────────────
// GET TODAY ALERTS
// ──────────────────────────────────────────────────────────────────────
router.get(
  '/today-alerts',
  controller.todayAlerts
);


// ──────────────────────────────────────────────────────────────────────
// GET BY ID
// ──────────────────────────────────────────────────────────────────────
router.get(
  '/:id',
  controller.getById
);


// ──────────────────────────────────────────────────────────────────────
// CREATE
// ──────────────────────────────────────────────────────────────────────
router.post(
  '/',
  controller.create
);


// ──────────────────────────────────────────────────────────────────────
// UPDATE
// ──────────────────────────────────────────────────────────────────────
router.put(
  '/:id',
  controller.update
);


// ──────────────────────────────────────────────────────────────────────
// MARK ALERT SENT
// ──────────────────────────────────────────────────────────────────────
router.patch(
  '/:id/mark-sent',
  controller.markSent
);


// ──────────────────────────────────────────────────────────────────────
// DELETE
// ──────────────────────────────────────────────────────────────────────
router.delete(
  '/:id',
  controller.remove
);


export default router;