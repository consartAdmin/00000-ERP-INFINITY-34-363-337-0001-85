export function normalizeItemForWrite(payload = {}) {
  const quantity = toNum(payload.quantity, 0);
  const unitPrice = toNum(payload.unit_price, 0);
  const totalPrice = toNum(payload.total_price, quantity * unitPrice);
  const ipiValue = toNum(payload.ipi_value ?? payload.ipi, 0);
  const icmsValue = toNum(payload.icms_value ?? payload.icms, 0);

  return {
    ...payload,
    inbound_id: payload.inbound_id ?? payload.invoice_id,
    nfe_item_seq: payload.nfe_item_seq,
    nf_product_code: String(payload.nf_product_code ?? payload.product_code ?? 'SEM-REFERENCIA').trim(),
    description: String(payload.description ?? 'ITEM SEM DESCRIÇÃO').trim(),
    unit: String(payload.unit ?? payload.commercial_unit ?? 'UN').trim().slice(0, 10),
    quantity,
    unit_price: unitPrice,
    total_price: totalPrice,
    commercial_unit: payload.commercial_unit ?? payload.unit ?? 'UN',
    commercial_quantity: payload.commercial_quantity ?? quantity,
    commercial_unit_price: payload.commercial_unit_price ?? unitPrice,
    taxable_unit: payload.taxable_unit ?? payload.unit ?? 'UN',
    taxable_quantity: payload.taxable_quantity ?? quantity,
    taxable_unit_price: payload.taxable_unit_price ?? unitPrice,
    conversion_factor: toNum(payload.conversion_factor, 1) || 1,
    gross_total: toNum(payload.gross_total, totalPrice),
    discount_value: toNum(payload.discount_value, 0),
    freight_value: toNum(payload.freight_value, 0),
    insurance_value: toNum(payload.insurance_value, 0),
    other_expenses: toNum(payload.other_expenses, 0),
    net_total: toNum(payload.net_total, totalPrice),
    ipi: ipiValue,
    ipi_value: ipiValue,
    icms: icmsValue,
    icms_value: icmsValue,
  };
}
