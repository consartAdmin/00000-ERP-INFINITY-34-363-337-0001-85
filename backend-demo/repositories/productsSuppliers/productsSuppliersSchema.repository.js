import pool from '../../config/db.js';
import { TB } from './productsSuppliers.constants.js';
import { ok, fail } from './productsSuppliers.utils.js';

/* ──────────────────────────────────────────────────────────────
   ensureProductsSuppliersTable
   → Implementação simples, sem ALTERs complexos
────────────────────────────────────────────────────────────── */
export async function ensureProductsSuppliersTable() {
  const client = await pool.connect();
  try {
    // 1) Cria tabela se não existir
    await client.query(`
      CREATE TABLE IF NOT EXISTS ${TB} (
        product_supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id          VARCHAR(100) NOT NULL,
        supplier_id         INTEGER NOT NULL,
        is_primary          BOOLEAN NOT NULL DEFAULT false,
        created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
      );
    `);

    // 2) Comentário (opcional)
    await client.query(`
      COMMENT ON TABLE ${TB} IS 'Relação Produto x Fornecedor (CONSART ERP)';
    `);

    // 3) Índice único: um mesmo fornecedor não se repete para o mesmo produto
    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS productsSuppliers_product_supplier_uq
        ON ${TB} (product_id, supplier_id);
    `);

    // 4) Índices auxiliares
    await client.query(`
      CREATE INDEX IF NOT EXISTS productsSuppliers_prod_idx
        ON ${TB} (product_id);
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS productsSuppliers_sup_idx
        ON ${TB} (supplier_id);
    `);

    console.log('[productsSuppliersApi] Tabela public."productsSuppliers" verificada/criada.');
    return ok(true);
  } catch (err) {
    console.error('[productsSuppliersApi] Erro ao garantir tabela productsSuppliers:', err);
    return fail(err.message || 'Erro ao garantir tabela productsSuppliers', 500);
  } finally {
    client.release();
  }
}
