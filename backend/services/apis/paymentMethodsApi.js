'use strict';

import pool from '../../config/db.js';

const SCHEMA = 'public';
const TABLE = 'paymentMethods';
const TB = `${SCHEMA}."${TABLE}"`;
const PK = '"paymentMethods_id"';
const ADVISORY_LOCK_KEY = 847521001;

const GAP_COLUMNS = [
  'gap_one', 'gap_two', 'gap_three', 'gap_four', 'gap_five',
  'gap_six', 'gap_seven', 'gap_eight', 'gap_nine', 'gap_ten',
];

const SELECT_COLUMNS = `
  ${PK} AS "paymentMethods_id",
  "name", "type", "installments",
  ${GAP_COLUMNS.map((column) => `"${column}"`).join(', ')},
  "nfe_tpag", "active", "created_at", "updated_at"
`;

let ensureTablePromise = null;

function toInt(value, fallback = 0) {
  const n = Number(value);
  return Number.isInteger(n) ? n : fallback;
}

function toBool(value) {
  if (typeof value === 'boolean') return value;
  const normalized = String(value ?? '').trim().toLowerCase();
  return ['1', 'true', 't', 'yes', 'y', 'sim', 's', 'on'].includes(normalized);
}

function cleanText(value, fallback = null) {
  if (value == null) return fallback;
  const normalized = String(value).trim();
  return normalized || fallback;
}

function normalizeGap(value) {
  if (value === '' || value == null) return null;
  return Math.max(0, toInt(value, 0));
}

function fromDb(row) {
  if (!row) return null;

  const id = Number(
    row.paymentMethods_id ??
    row.paymentmethods_id ??
    row.payment_method_id ??
    row.id
  );

  const result = {
    id,
    paymentMethods_id: id,
    name: row.name ?? '',
    type: row.type ?? '',
    installments: Number(row.installments ?? 1) || 1,
    nfe_tpag: row.nfe_tpag?.trim() || null,
    active: Boolean(row.active),
    created_at: row.created_at ?? null,
    updated_at: row.updated_at ?? null,
  };

  for (const column of GAP_COLUMNS) {
    result[column] = row[column] == null ? null : Number(row[column]);
  }

  return result;
}

function normalizePayload(payload = {}) {
  const result = {
    name: cleanText(payload.name, ''),
    type: cleanText(payload.type, ''),
    installments: toInt(payload.installments, 1),
    nfe_tpag: cleanText(payload.nfe_tpag, null),
    active: typeof payload.active === 'undefined' ? true : toBool(payload.active),
  };

  for (const column of GAP_COLUMNS) {
    result[column] = normalizeGap(payload[column]);
  }

  return result;
}

function validatePayload(payload) {
  if (!cleanText(payload.name, '')) {
    throw new Error('O campo "name" é obrigatório.');
  }

  if (!cleanText(payload.type, '')) {
    throw new Error('O campo "type" é obrigatório.');
  }

  if (!Number.isInteger(payload.installments) || payload.installments < 1 || payload.installments > 10) {
    throw new Error('O campo "installments" deve ser um inteiro entre 1 e 10.');
  }

  if (payload.nfe_tpag != null && !/^\d{2}$/.test(payload.nfe_tpag)) {
    throw new Error('O campo "nfe_tpag" deve possuir exatamente dois dígitos.');
  }
}

export async function ensureTable() {
  if (ensureTablePromise) return ensureTablePromise;

  ensureTablePromise = (async () => {
    const client = await pool.connect();

    try {
      await client.query('BEGIN');
      await client.query('SELECT pg_advisory_xact_lock($1)', [ADVISORY_LOCK_KEY]);

      await client.query(`
        CREATE TABLE IF NOT EXISTS ${TB} (
          ${PK} INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "name" VARCHAR(100) NOT NULL,
          "type" VARCHAR(100) NOT NULL,
          "installments" INTEGER NOT NULL DEFAULT 1,
          "gap_one" INTEGER DEFAULT 0,
          "gap_two" INTEGER DEFAULT 0,
          "gap_three" INTEGER DEFAULT 0,
          "gap_four" INTEGER DEFAULT 0,
          "gap_five" INTEGER DEFAULT 0,
          "gap_six" INTEGER DEFAULT 0,
          "gap_seven" INTEGER DEFAULT 0,
          "gap_eight" INTEGER DEFAULT 0,
          "gap_nine" INTEGER DEFAULT 0,
          "gap_ten" INTEGER DEFAULT 0,
          "active" BOOLEAN NOT NULL DEFAULT TRUE,
          "created_at" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
          "updated_at" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
          "nfe_tpag" CHAR(2)
        );
      `);

      await client.query(`ALTER TABLE ${TB} ADD COLUMN IF NOT EXISTS "type" VARCHAR(100) NOT NULL DEFAULT '';`);
      await client.query(`ALTER TABLE ${TB} ADD COLUMN IF NOT EXISTS "installments" INTEGER NOT NULL DEFAULT 1;`);

      for (const column of GAP_COLUMNS) {
        await client.query(`ALTER TABLE ${TB} ADD COLUMN IF NOT EXISTS "${column}" INTEGER DEFAULT 0;`);
      }

      await client.query(`ALTER TABLE ${TB} ADD COLUMN IF NOT EXISTS "nfe_tpag" CHAR(2);`);
      await client.query(`ALTER TABLE ${TB} ADD COLUMN IF NOT EXISTS "active" BOOLEAN NOT NULL DEFAULT TRUE;`);
      await client.query(`ALTER TABLE ${TB} ADD COLUMN IF NOT EXISTS "created_at" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;`);
      await client.query(`ALTER TABLE ${TB} ADD COLUMN IF NOT EXISTS "updated_at" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;`);

      await client.query(`CREATE INDEX IF NOT EXISTS "idx_paymentMethods_name" ON ${TB} (LOWER("name"));`);
      await client.query(`CREATE INDEX IF NOT EXISTS "idx_paymentMethods_type" ON ${TB} (LOWER("type"));`);
      await client.query(`CREATE INDEX IF NOT EXISTS "idx_paymentMethods_active" ON ${TB} ("active");`);
      await client.query(`CREATE INDEX IF NOT EXISTS "idx_paymentMethods_nfe_tpag" ON ${TB} ("nfe_tpag");`);

      await client.query(`
        CREATE OR REPLACE FUNCTION ${SCHEMA}.set_updated_at_payment_methods()
        RETURNS trigger
        LANGUAGE plpgsql
        AS $$
        BEGIN
          NEW."updated_at" := CURRENT_TIMESTAMP;
          RETURN NEW;
        END;
        $$;
      `);

      await client.query(`DROP TRIGGER IF EXISTS "trg_paymentMethods_updated_at" ON ${TB};`);
      await client.query(`
        CREATE TRIGGER "trg_paymentMethods_updated_at"
        BEFORE UPDATE ON ${TB}
        FOR EACH ROW
        EXECUTE FUNCTION ${SCHEMA}.set_updated_at_payment_methods();
      `);

      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  })();

  try {
    return await ensureTablePromise;
  } finally {
    ensureTablePromise = null;
  }
}

export async function getById(id) {
  const safeId = toInt(id, 0);
  if (!safeId) throw new Error('ID inválido.');

  const { rows } = await pool.query(`
    SELECT ${SELECT_COLUMNS}
    FROM ${TB}
    WHERE ${PK} = $1
    LIMIT 1;
  `, [safeId]);

  return rows[0] ? fromDb(rows[0]) : null;
}

export async function list({ q = '', active, limit = 50, offset = 0 } = {}) {
  const where = [];
  const values = [];
  let parameter = 1;

  const search = String(q || '').trim();
  const safeLimit = Math.min(200, Math.max(1, toInt(limit, 50)));
  const safeOffset = Math.max(0, toInt(offset, 0));

  if (search) {
    where.push(`(LOWER("name") LIKE $${parameter} OR LOWER("type") LIKE $${parameter})`);
    values.push(`%${search.toLowerCase()}%`);
    parameter += 1;
  }

  if (typeof active !== 'undefined' && active !== null && active !== '') {
    where.push(`"active" = $${parameter}`);
    values.push(toBool(active));
    parameter += 1;
  }

  const whereSql = where.length ? `WHERE ${where.join(' AND ')}` : '';

  const [dataResult, totalResult] = await Promise.all([
    pool.query(`
      SELECT ${SELECT_COLUMNS}
      FROM ${TB}
      ${whereSql}
      ORDER BY "active" DESC, LOWER("name") ASC
      LIMIT $${parameter} OFFSET $${parameter + 1};
    `, [...values, safeLimit, safeOffset]),
    pool.query(`SELECT COUNT(*)::int AS total FROM ${TB} ${whereSql};`, values),
  ]);

  return {
    rows: dataResult.rows.map(fromDb),
    total: totalResult.rows[0]?.total ?? 0,
    limit: safeLimit,
    offset: safeOffset,
  };
}

export async function create(payload = {}) {
  const data = normalizePayload(payload);
  validatePayload(data);

  const columns = ['name', 'type', 'installments', ...GAP_COLUMNS, 'nfe_tpag', 'active'];
  const values = columns.map((column) => data[column]);
  const placeholders = columns.map((_, index) => `$${index + 1}`).join(', ');

  const { rows } = await pool.query(`
    INSERT INTO ${TB} (${columns.map((column) => `"${column}"`).join(', ')})
    VALUES (${placeholders})
    RETURNING ${SELECT_COLUMNS};
  `, values);

  return fromDb(rows[0]);
}

export async function update(id, payload = {}) {
  const safeId = toInt(id, 0);
  if (!safeId) throw new Error('ID inválido.');

  const current = await getById(safeId);
  if (!current) return null;

  const data = normalizePayload({ ...current, ...payload });
  validatePayload(data);

  const columns = ['name', 'type', 'installments', ...GAP_COLUMNS, 'nfe_tpag', 'active'];
  const assignments = columns.map((column, index) => `"${column}" = $${index + 2}`).join(', ');
  const values = [safeId, ...columns.map((column) => data[column])];

  const { rows } = await pool.query(`
    UPDATE ${TB}
    SET ${assignments}
    WHERE ${PK} = $1
    RETURNING ${SELECT_COLUMNS};
  `, values);

  return rows[0] ? fromDb(rows[0]) : null;
}

export async function remove(id) {
  const safeId = toInt(id, 0);
  if (!safeId) throw new Error('ID inválido.');

  const { rows } = await pool.query(`
    DELETE FROM ${TB}
    WHERE ${PK} = $1
    RETURNING ${SELECT_COLUMNS};
  `, [safeId]);

  return rows[0] ? fromDb(rows[0]) : null;
}

export async function toggleActive(id, active) {
  const safeId = toInt(id, 0);
  if (!safeId) throw new Error('ID inválido.');

  const { rows } = await pool.query(`
    UPDATE ${TB}
    SET "active" = $2
    WHERE ${PK} = $1
    RETURNING ${SELECT_COLUMNS};
  `, [safeId, toBool(active)]);

  return rows[0] ? fromDb(rows[0]) : null;
}

export default { ensureTable, getById, list, create, update, remove, toggleActive };