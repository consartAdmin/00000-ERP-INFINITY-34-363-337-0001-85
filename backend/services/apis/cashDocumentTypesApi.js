'use strict';

import pool from '../../config/db.js';

const TABLE = 'public."cashDocumentTypes"';

function normalizeName(value) {
  return String(value ?? '').trim().replace(/\s+/g, ' ');
}

function normalizeId(value) {
  const id = Number.parseInt(value, 10);
  return Number.isInteger(id) && id > 0 ? id : null;
}

function normalizeBoolean(value, fallback = true) {
  if (typeof value === 'boolean') return value;
  if (value === 'true' || value === '1' || value === 1) return true;
  if (value === 'false' || value === '0' || value === 0) return false;
  return fallback;
}

export async function ensureCashDocumentTypesTable(client = pool) {
  await client.query(`
    CREATE TABLE IF NOT EXISTS ${TABLE} (
      id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name        VARCHAR(100) NOT NULL,
      is_active   BOOLEAN NOT NULL DEFAULT TRUE,
      created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
      updated_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
      CONSTRAINT "cashDocumentTypes_name_key" UNIQUE (name)
    )
  `);

  await client.query(`
    CREATE INDEX IF NOT EXISTS "idx_cashDocumentTypes_active_name"
      ON ${TABLE} (is_active, name)
  `);
}

export async function seedCashDocumentTypes(client = pool) {
  await ensureCashDocumentTypesTable(client);

  const names = ['NF-e', 'Cupom Fiscal', 'Outro', 'NFS-e', 'Boleto'];

  const { rows } = await client.query(
    `
      INSERT INTO ${TABLE} (name)
      SELECT name
        FROM UNNEST($1::VARCHAR[]) AS source(name)
      ON CONFLICT (name) DO UPDATE
        SET is_active = TRUE,
            updated_at = NOW()
      RETURNING id, name, is_active, created_at, updated_at
    `,
    [names]
  );

  return rows;
}

export async function listCashDocumentTypes(filters = {}) {
  const search = String(filters.search ?? '').trim();
  const activeOnly = normalizeBoolean(filters.activeOnly, false);
  const includeInactive = normalizeBoolean(filters.includeInactive, true);

  const values = [];
  const where = [];

  if (search) {
    values.push(`%${search}%`);
    where.push(`name ILIKE $${values.length}`);
  }

  if (activeOnly || !includeInactive) {
    where.push('is_active = TRUE');
  }

  const whereSql = where.length ? `WHERE ${where.join(' AND ')}` : '';

  const { rows } = await pool.query(
    `
      SELECT id, name, is_active, created_at, updated_at
        FROM ${TABLE}
        ${whereSql}
       ORDER BY is_active DESC, name ASC, id ASC
    `,
    values
  );

  return rows;
}

export async function getCashDocumentTypeById(idValue) {
  const id = normalizeId(idValue);
  if (!id) return null;

  const { rows } = await pool.query(
    `
      SELECT id, name, is_active, created_at, updated_at
        FROM ${TABLE}
       WHERE id = $1
       LIMIT 1
    `,
    [id]
  );

  return rows[0] ?? null;
}

export async function createCashDocumentType(payload = {}) {
  const name = normalizeName(payload.name);
  const isActive = normalizeBoolean(payload.is_active, true);

  if (!name) {
    const error = new Error('Informe o nome do tipo de documento.');
    error.statusCode = 400;
    throw error;
  }

  const duplicate = await pool.query(
    `SELECT id FROM ${TABLE} WHERE LOWER(name) = LOWER($1) LIMIT 1`,
    [name]
  );

  if (duplicate.rowCount) {
    const error = new Error('Já existe um tipo de documento com esse nome.');
    error.statusCode = 409;
    throw error;
  }

  const { rows } = await pool.query(
    `
      INSERT INTO ${TABLE} (name, is_active)
      VALUES ($1, $2)
      RETURNING id, name, is_active, created_at, updated_at
    `,
    [name, isActive]
  );

  return rows[0];
}

export async function updateCashDocumentType(idValue, payload = {}) {
  const id = normalizeId(idValue);
  if (!id) {
    const error = new Error('ID inválido.');
    error.statusCode = 400;
    throw error;
  }

  const current = await getCashDocumentTypeById(id);
  if (!current) return null;

  const name = payload.name === undefined
    ? current.name
    : normalizeName(payload.name);

  const isActive = payload.is_active === undefined
    ? current.is_active
    : normalizeBoolean(payload.is_active, current.is_active);

  if (!name) {
    const error = new Error('Informe o nome do tipo de documento.');
    error.statusCode = 400;
    throw error;
  }

  const duplicate = await pool.query(
    `
      SELECT id
        FROM ${TABLE}
       WHERE LOWER(name) = LOWER($1)
         AND id <> $2
       LIMIT 1
    `,
    [name, id]
  );

  if (duplicate.rowCount) {
    const error = new Error('Já existe um tipo de documento com esse nome.');
    error.statusCode = 409;
    throw error;
  }

  const { rows } = await pool.query(
    `
      UPDATE ${TABLE}
         SET name = $1,
             is_active = $2,
             updated_at = NOW()
       WHERE id = $3
       RETURNING id, name, is_active, created_at, updated_at
    `,
    [name, isActive, id]
  );

  return rows[0] ?? null;
}

export async function setCashDocumentTypeActive(idValue, isActiveValue) {
  const id = normalizeId(idValue);
  if (!id) {
    const error = new Error('ID inválido.');
    error.statusCode = 400;
    throw error;
  }

  const isActive = normalizeBoolean(isActiveValue, false);

  const { rows } = await pool.query(
    `
      UPDATE ${TABLE}
         SET is_active = $1,
             updated_at = NOW()
       WHERE id = $2
       RETURNING id, name, is_active, created_at, updated_at
    `,
    [isActive, id]
  );

  return rows[0] ?? null;
}

export async function toggleCashDocumentTypeActive(idValue) {
  const id = normalizeId(idValue);
  if (!id) {
    const error = new Error('ID inválido.');
    error.statusCode = 400;
    throw error;
  }

  const { rows } = await pool.query(
    `
      UPDATE ${TABLE}
         SET is_active = NOT is_active,
             updated_at = NOW()
       WHERE id = $1
       RETURNING id, name, is_active, created_at, updated_at
    `,
    [id]
  );

  return rows[0] ?? null;
}

// Exclusão lógica para preservar vínculos históricos de Contas a Pagar.
export async function removeCashDocumentType(idValue) {
  return setCashDocumentTypeActive(idValue, false);
}
