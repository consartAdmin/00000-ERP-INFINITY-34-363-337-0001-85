import pool from '../../config/db.js';

/* ──────────────────────────────────────────────────────────────
   Tabela & Alias
────────────────────────────────────────────────────────────── */
const TB    = 'public."productsSuppliers"';
const ALIAS = 'ps';

/* ──────────────────────────────────────────────────────────────
   Helpers comuns
────────────────────────────────────────────────────────────── */
const ok   = (data) => ({ ok: true, data });
const fail = (error, status = 400) => ({ ok: false, error, status });

function normalizeRow(r = {}) {
  return {
    product_supplier_id: r.product_supplier_id,
    product_id: String(r.product_id),
    supplier_id: Number(r.supplier_id),
    is_primary: !!r.is_primary,
    created_at: r.created_at,
  };
}

/* ──────────────────────────────────────────────────────────────
   ensureProductsSuppliersTable
   → Implementação simples, sem ALTERs complexos
────────────────────────────────────────────────────────────── */
export async function ensureProductsSuppliersTable() {
  const client = await pool.connect();
  try {
    // 1) Cria tabela se não existir
    await client.query(`
      CREATE TABLE IF NOT EXISTS ${TB} (
        product_supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id          VARCHAR(100) NOT NULL,
        supplier_id         INTEGER NOT NULL,
        is_primary          BOOLEAN NOT NULL DEFAULT false,
        created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
      );
    `);

    // 2) Comentário (opcional)
    await client.query(`
      COMMENT ON TABLE ${TB} IS 'Relação Produto x Fornecedor (CONSART ERP)';
    `);

    // 3) Índice único: um mesmo fornecedor não se repete para o mesmo produto
    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS productsSuppliers_product_supplier_uq
        ON ${TB} (product_id, supplier_id);
    `);

    // 4) Índices auxiliares
    await client.query(`
      CREATE INDEX IF NOT EXISTS productsSuppliers_prod_idx
        ON ${TB} (product_id);
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS productsSuppliers_sup_idx
        ON ${TB} (supplier_id);
    `);

    console.log('[productsSuppliersApi] Tabela public."productsSuppliers" verificada/criada.');
    return ok(true);
  } catch (err) {
    console.error('[productsSuppliersApi] Erro ao garantir tabela productsSuppliers:', err);
    return fail(err.message || 'Erro ao garantir tabela productsSuppliers', 500);
  } finally {
    client.release();
  }
}

/* ──────────────────────────────────────────────────────────────
   list — compatível com controller antigo
   - Se passar product_id  → delega p/ listByProduct
   - Se passar supplier_id → delega p/ listBySupplier
   - Senão, lista tudo com paginação
────────────────────────────────────────────────────────────── */
export async function list({
  page = 1,
  limit = 50,
  product_id,
  supplier_id,
} = {}) {
  // Atalhos: se vierem filtros específicos, usa funções dedicadas
  if (product_id) {
    return listByProduct(product_id);
  }
  if (supplier_id) {
    return listBySupplier(supplier_id);
  }

  try {
    const pg = Number(page) > 0 ? Number(page) : 1;
    const lim =
      Number(limit) > 0 && Number(limit) <= 1000 ? Number(limit) : 50;
    const offset = (pg - 1) * lim;

    const params = [lim, offset];

    const sql = `
      SELECT
        ${ALIAS}.product_supplier_id,
        ${ALIAS}.product_id,
        ${ALIAS}.supplier_id,
        ${ALIAS}.is_primary,
        ${ALIAS}.created_at,
        COUNT(*) OVER() AS total_count
      FROM ${TB} ${ALIAS}
      ORDER BY ${ALIAS}.product_id ASC, ${ALIAS}.supplier_id ASC
      LIMIT $1
      OFFSET $2
    `;

    const { rows } = await pool.query(sql, params);
    const total = rows.length ? Number(rows[0].total_count) : 0;
    const dataRows = rows.map(normalizeRow);

    return ok({
      rows: dataRows,
      total,
      page: pg,
      limit: lim,
    });
  } catch (err) {
    console.error('[productsSuppliersApi:list] error:', err);
    return fail('Erro ao listar vínculos produto x fornecedor.', 500);
  }
}

/* ──────────────────────────────────────────────────────────────
   listByProduct — lista fornecedores de um produto
────────────────────────────────────────────────────────────── */
export async function listByProduct(productId) {
  const pid = String(productId ?? '').trim();
  if (!pid) return fail('productId é obrigatório.', 400);

  try {
    const { rows } = await pool.query(
      `
      SELECT
        ${ALIAS}.product_supplier_id,
        ${ALIAS}.product_id,
        ${ALIAS}.supplier_id,
        ${ALIAS}.is_primary,
        ${ALIAS}.created_at
      FROM ${TB} ${ALIAS}
      WHERE ${ALIAS}.product_id = $1
      ORDER BY ${ALIAS}.is_primary DESC, ${ALIAS}.supplier_id ASC
      `,
      [pid]
    );

    const data = rows.map(normalizeRow);
    return ok(data);
  } catch (err) {
    console.error('[productsSuppliersApi:listByProduct] error:', err);
    return fail('Erro ao listar fornecedores do produto.', 500);
  }
}

/* ──────────────────────────────────────────────────────────────
   listBySupplier — lista produtos de um fornecedor
────────────────────────────────────────────────────────────── */
export async function listBySupplier(supplierId) {
  const sid = Number(supplierId);
  if (!Number.isInteger(sid) || sid <= 0) {
    return fail('supplierId inválido.', 400);
  }

  try {
    const { rows } = await pool.query(
      `
      SELECT
        ${ALIAS}.product_supplier_id,
        ${ALIAS}.product_id,
        ${ALIAS}.supplier_id,
        ${ALIAS}.is_primary,
        ${ALIAS}.created_at
      FROM ${TB} ${ALIAS}
      WHERE ${ALIAS}.supplier_id = $1
      ORDER BY ${ALIAS}.product_id ASC
      `,
      [sid]
    );

    const data = rows.map(normalizeRow);
    return ok(data);
  } catch (err) {
    console.error('[productsSuppliersApi:listBySupplier] error:', err);
    return fail('Erro ao listar produtos do fornecedor.', 500);
  }
}

/* ──────────────────────────────────────────────────────────────
   addLink — adiciona (ou garante) vínculo produto x fornecedor
────────────────────────────────────────────────────────────── */
export async function addLink({
  product_id,
  supplier_id,
  is_primary = false,
} = {}) {
  const pid = String(product_id ?? '').trim();
  const sid = Number(supplier_id);

  if (!pid) return fail('product_id é obrigatório.', 400);
  if (!Number.isInteger(sid) || sid <= 0) return fail('supplier_id inválido.', 400);

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    if (is_primary) {
      // Se esse fornecedor for o principal, zera os outros do mesmo produto
      await client.query(
        `
        UPDATE ${TB}
        SET is_primary = false
        WHERE product_id = $1
        `,
        [pid]
      );
    }

    const { rows } = await client.query(
      `
      INSERT INTO ${TB} (product_id, supplier_id, is_primary)
      VALUES ($1, $2, $3)
      ON CONFLICT (product_id, supplier_id)
      DO UPDATE SET
        is_primary = EXCLUDED.is_primary
      RETURNING
        product_supplier_id,
        product_id,
        supplier_id,
        is_primary,
        created_at
      `,
      [pid, sid, !!is_primary]
    );

    await client.query('COMMIT');
    return ok(normalizeRow(rows[0]));
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('[productsSuppliersApi:addLink] error:', err);
    return fail('Erro ao vincular fornecedor ao produto.', 500);
  } finally {
    client.release();
  }
}

/* ──────────────────────────────────────────────────────────────
   setPrimary — marca um vínculo como principal
────────────────────────────────────────────────────────────── */
export async function setPrimary(product_supplier_id) {
  const id = Number(product_supplier_id);
  if (!Number.isInteger(id) || id <= 0) {
    return fail('product_supplier_id inválido.', 400);
  }

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    // Descobre qual é o product_id desse vínculo
    const { rows: curRows } = await client.query(
      `
      SELECT product_id
      FROM ${TB}
      WHERE product_supplier_id = $1
      `,
      [id]
    );

    if (!curRows.length) {
      await client.query('ROLLBACK');
      return fail('Vínculo não encontrado.', 404);
    }

    const pid = String(curRows[0].product_id);

    // Zera todos como não principais
    await client.query(
      `
      UPDATE ${TB}
      SET is_primary = false
      WHERE product_id = $1
      `,
      [pid]
    );

    // Marca o solicitado como principal
    const { rows } = await client.query(
      `
      UPDATE ${TB}
      SET is_primary = true
      WHERE product_supplier_id = $1
      RETURNING
        product_supplier_id,
        product_id,
        supplier_id,
        is_primary,
        created_at
      `,
      [id]
    );

    await client.query('COMMIT');

    if (!rows.length) {
      return fail('Vínculo não encontrado após atualização.', 404);
    }

    return ok(normalizeRow(rows[0]));
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('[productsSuppliersApi:setPrimary] error:', err);
    return fail('Erro ao definir fornecedor principal.', 500);
  } finally {
    client.release();
  }
}

/* ──────────────────────────────────────────────────────────────
   remove — remove vínculo produto x fornecedor
────────────────────────────────────────────────────────────── */
export async function remove(product_supplier_id) {
  const id = Number(product_supplier_id);
  if (!Number.isInteger(id) || id <= 0) {
    return fail('product_supplier_id inválido.', 400);
  }

  try {
    const { rowCount } = await pool.query(
      `
      DELETE FROM ${TB}
      WHERE product_supplier_id = $1
      `,
      [id]
    );

    if (rowCount === 0) {
      return fail('Vínculo não encontrado.', 404);
    }

    return ok({ product_supplier_id: id });
  } catch (err) {
    console.error('[productsSuppliersApi:remove] error:', err);
    return fail('Erro ao remover vínculo produto x fornecedor.', 500);
  }
}

